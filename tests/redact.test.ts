import { describe, expect, it } from 'vitest';

import { redact } from '../src/modules/ai/contracts/redact.js';

describe('redact masks personal data before it leaves for the model', () => {
    it.each([
        ['Пишите на ivan.petrov@mail.ru', 'Пишите на [EMAIL]'],
        ['Мой номер +7 (912) 345-67-89', 'Мой номер [ТЕЛЕФОН]'],
        ['звоните 89123456789', 'звоните [ТЕЛЕФОН]'],
        ['или 79123456789', 'или [ТЕЛЕФОН]'],
        ['мобильный 912 345-67-89', 'мобильный [ТЕЛЕФОН]'],
        ['Номер в Беларуси +375 29 123-45-67', 'Номер в Беларуси [ТЕЛЕФОН]'],
        ['паспорт 4510 123456', 'паспорт [ПАСПОРТ]'],
        ['Паспортные данные: 45 10 № 123456', 'Паспортные данные: [ПАСПОРТ]'],
        ['серия 4510 номер 123456', '[ПАСПОРТ]'],
        ['код подразделения 770-001', 'код подразделения [ПАСПОРТ]'],
        ['СНИЛС 112-233-445 95', 'СНИЛС [СНИЛС]'],
        ['снилс: 11223344595', 'снилс: [СНИЛС]'],
        ['ИНН 7707083893', 'ИНН [ИНН]'],
        ['мой инн: 500100732259', 'мой инн: [ИНН]'],
        ['полис ОМС 1234567890123456', 'полис ОМС [ПОЛИС]'],
        ['дата рождения 01.02.1990', 'дата рождения [ДАТА РОЖДЕНИЯ]'],
        ['Карта 4276 3800 1234 5678 списала дважды', 'Карта [КАРТА] списала дважды'],
        ['списали с 4111 1111 1111 1111', 'списали с [КАРТА]'],
        ['карта 4111111111111111', 'карта [КАРТА]'],
        ['р/с 40817810099910004312', 'р/с [СЧЁТ]'],
        ['CVV 123', 'CVV [СЕКРЕТ]'],
        ['код из смс 4821', 'код из смс [СЕКРЕТ]'],
        ['пароль: qwerty123', 'пароль: [СЕКРЕТ]'],
        ['token=sk-abcdefghijklmnop', 'token=[СЕКРЕТ]'],
        ['ул. Ленина, д. 5, кв. 12', 'ул. Ленина, д. [ДОМ], кв. [КВ]'],
        ['улица Мира 15-42, нет интернета', 'улица Мира [ДОМ], нет интернета'],
        ['пр-т Свободный, дом 28/1, корп. 2, офис 305', 'пр-т Свободный, дом [ДОМ], корп. [ДОМ], офис [КВ]'],
    ])('%s', (input, expected) => {
        expect(redact(input)).toBe(expected);
    });

    it.each([
        'Обращение №000123 по договору 123456',
        'Скорость 100 Мбит/с вместо 500',
        'IP 192.168.0.1, шлюз 10.0.0.1',
        'Сбой с 15.10.2026 по 16.10.2026',
        'Площадь 50 кв. м, роутер в коридоре',
        '1 500 000 рублей и 12345678901234 без Luhn',
        'пароль не подходит, сбросьте',
        'и т.д. и т.п.',
    ])('keeps %s', (input) => {
        expect(redact(input)).toBe(input);
    });
});
